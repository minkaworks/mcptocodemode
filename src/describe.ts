import { findServer, findTool } from "./catalog.js";
import { inputType, schemaToType } from "./schema.js";
import type { Catalog, ServerNamespace, ToolRecord } from "./types.js";

function comment(description: string, max: number): string {
  const text = description.replace(/\*\//g, "* /").trim();
  if (!text) return "";
  const clipped = text.length > max ? `${text.slice(0, max - 1)}…` : text;
  const lines = clipped.split("\n");
  if (lines.length === 1) return `/** ${lines[0]} */\n`;
  return `/**\n${lines.map((line) => ` * ${line}`).join("\n")}\n */\n`;
}

function signature(name: string, tool: ToolRecord, docChars: number): string {
  const input = inputType(tool.inputSchema, { docChars });
  const optional = input.optional ? "?" : "";
  const header = comment(tool.description, docChars === 160 ? 160 : 2000);
  return `${header}${name}(input${optional}: ${input.type}): Promise<${outputType(tool, docChars)}>;`;
}

/** One-line-per-property call signature without the doc header, for search hits. */
export function compactSignature(server: ServerNamespace, tool: ToolRecord): string {
  const input = inputType(tool.inputSchema, { docChars: 80 });
  return `${server.ident}.${tool.method}(input${input.optional ? "?" : ""}: ${input.type}): Promise<${outputType(tool, 80)}>`;
}

/** The resolved value's type. `unknown` when the server declares no output schema. */
function outputType(tool: ToolRecord, docChars: number): string {
  return tool.outputSchema ? schemaToType(tool.outputSchema, 1, { docChars }) : "unknown";
}

function renderMethod(server: ServerNamespace, tool: ToolRecord, docChars: number): string {
  return signature(`${server.ident}.${tool.method}`, tool, docChars);
}

function indent(block: string): string {
  return block.replace(/^/gm, "  ");
}

const PROTOCOL_GROUPS = ["resources", "prompts"] as const;

const SERVER_CHAR_BUDGET = 24_000;

export function describeTarget(catalog: Catalog, target: string): string {
  const trimmed = target.trim();
  if (!trimmed) {
    throw new Error('describe needs a target like "notes" or "notes.get"');
  }
  const dot = trimmed.indexOf(".");
  const serverName = dot === -1 ? trimmed : trimmed.slice(0, dot);
  const methodName = dot === -1 ? undefined : trimmed.slice(dot + 1);
  const server = findServer(catalog, serverName);
  if (!server) {
    const known = catalog.servers.map((item) => item.ident).join(", ") || "(none)";
    throw new Error(`Unknown server "${serverName}". Known servers: ${known}`);
  }
  if (server.error && methodName) throw new Error(`${server.ident} did not connect: ${server.error}`);
  if (!methodName) return renderServer(server);
  const tool = findTool(server, methodName);
  if (!tool) {
    const known = server.tools.map((item) => item.method).join(", ");
    throw new Error(`Unknown method "${methodName}" on ${server.ident}. Methods: ${known}`);
  }
  return renderMethod(server, tool, 800);
}

function renderServer(server: ServerNamespace): string {
  if (server.error) {
    return `declare const ${server.ident}: {};\n// ${server.ident} did not connect: ${server.error}`;
  }
  // Members of an object type, so the output is a valid declaration file.
  // Protocol methods nest under `resources` and `prompts`, as they do in the sandbox.
  const blocks: string[] = [];
  for (const group of PROTOCOL_GROUPS) {
    const members = server.tools
      .filter((tool) => tool.kind === "protocol" && tool.method.startsWith(`${group}.`))
      .map((tool) => indent(signature(tool.method.slice(group.length + 1), tool, 160)));
    if (members.length > 0) blocks.push(`${group}: {\n${members.join("\n")}\n};`);
  }
  let used = blocks.reduce((sum, block) => sum + block.length, 0);
  let hidden = 0;
  for (const tool of server.tools) {
    if (tool.kind === "protocol") continue;
    const block = signature(tool.method, tool, 160);
    if (used + block.length > SERVER_CHAR_BUDGET && blocks.length > PROTOCOL_GROUPS.length) {
      hidden += 1;
      continue;
    }
    blocks.push(block);
    used += block.length;
  }
  const hiddenNote =
    hidden > 0
      ? `\n\n// ${hidden} more methods omitted. Call describe("${server.ident}.method") for one signature.`
      : "";
  return `declare const ${server.ident}: {\n${blocks.map(indent).join("\n")}\n};${hiddenNote}`;
}

export function renderSdk(catalog: Catalog): string {
  const header = `// Generated by mcptocodemode. Do not edit.\n// Inside execute(), call these methods. They return Promises.\n`;
  if (catalog.servers.length === 0) return `${header}\n// No upstream servers are connected.\n`;
  return `${header}\n${catalog.servers.map((server) => describeTarget(catalog, server.ident)).join("\n\n")}\n`;
}
